"""
Урок 6.2 "group и chord", шаг 5

Смоделируйте аккорд. Группа состоит из задач `square(n)`. Для неотрицательного n задача возвращает
`n * n`, для отрицательного падает с `ValueError`.

В первой строке колбэк `sum`, `max` или `count` (число результатов). Во второй аргументы задач
группы через пробел.

Если все задачи выполнились, выведите `результаты группы: [...]` (список Python в порядке задач) и
`колбэк: значение`. Если хотя бы одна задача упала, выведите `задача k упала: ValueError` для первой
такой задачи по порядку (k с единицы) и `колбэк не вызван`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    sum
    3 1 2

Пример вывода:

    результаты группы: [9, 1, 4]
    sum: 14
"""

# Решение
callback = input()
numbers = list(map(int, input().split()))
failed = [i for i, n in enumerate(numbers, 1) if n < 0]
if failed:
    print(f"задача {failed[0]} упала: ValueError")
    print("колбэк не вызван")
else:
    results = [n * n for n in numbers]
    print(f"результаты группы: {results}")
    value = {"sum": sum, "max": max, "count": len}[callback](results)
    print(f"{callback}: {value}")
