"""
Урок 12.2 "Лимиты, повторы и стоимость", шаг 5

Посчитайте паузу перед повтором, как задача `summarize`.

До конца ввода идут строки, в каждой номер повтора k (с нуля) и значение заголовка `Retry-After` в
секундах или `-`, если заголовка не было.

Для каждой строки выведите паузу в секундах. Если сервис назвал паузу, это она. Иначе пауза равна 5
× 2 в степени k, но не больше 60.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    0 -
    1 -
    2 15
    4 -

Пример вывода:

    5
    10
    15
    60
"""

# Решение
import sys

for line in sys.stdin:
    retries, retry_after = line.split()
    if retry_after == "-":
        print(min(60, 5 * 2 ** int(retries)))
    else:
        print(int(retry_after))
