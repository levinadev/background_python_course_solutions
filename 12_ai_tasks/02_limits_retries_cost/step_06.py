"""
Урок 12.2 "Лимиты, повторы и стоимость", шаг 6

Смоделируйте, чем закончится задача `summarize`.

В первой строке `max_retries`. Во второй через пробел ответы сервиса модели на попытки по порядку.
`200` значит, пересказ получен, `400` и `404` постоянные ошибки, `429` и `503` временные. У
временной ошибки может быть пауза из `Retry-After`, она записана через двоеточие, например `429:15`.

Если ответ 200, выведите `попытка k: 200, пересказ готов`. Постоянная ошибка даёт `попытка k: код,
FAILURE`. При временной ошибке, если повторов было меньше `max_retries`, выведите `попытка k: код,
повтор через p с` с паузой по правилам предыдущей задачи, иначе `попытка k: код, отчёт без
пересказа`. После строки без повтора попыток больше нет, лишние ответы не используются.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    2
    429:15 503 200

Пример вывода:

    попытка 1: 429, повтор через 15 с
    попытка 2: 503, повтор через 10 с
    попытка 3: 200, пересказ готов
"""

# Решение
max_retries = int(input())
answers = input().split()

retries = 0
for attempt, answer in enumerate(answers, 1):
    status, _, retry_after = answer.partition(":")
    if status == "200":
        print(f"попытка {attempt}: 200, пересказ готов")
        break
    if status in ("400", "404"):
        print(f"попытка {attempt}: {status}, FAILURE")
        break
    if retries >= max_retries:
        print(f"попытка {attempt}: {status}, отчёт без пересказа")
        break
    pause = int(retry_after) if retry_after else min(60, 5 * 2 ** retries)
    print(f"попытка {attempt}: {status}, повтор через {pause} с")
    retries += 1
