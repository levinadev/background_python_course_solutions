"""
Урок 12.2 "Лимиты, повторы и стоимость", шаг 7

Разные пользователи заказали отчёты и попросили их пересказать. Отчёты за один и тот же месяц
одинаковые, поэтому и запрос к модели у них одинаковый.

До конца ввода идут строки с номером отчёта и месяцем в порядке запросов на пересказ. Для каждой
строки выведите `номер: модель`, если такой запрос встретился впервые, и `номер: кэш`, если ответ
уже сохранён. Последней строкой выведите `запросов к модели: n`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    r1 2026-07
    r2 2026-07
    r3 2026-08

Пример вывода:

    r1: модель
    r2: кэш
    r3: модель
    запросов к модели: 2
"""

# Решение
import sys

cache = set()
paid = 0
for line in sys.stdin:
    report_id, month = line.split()
    if month in cache:
        print(f"{report_id}: кэш")
    else:
        cache.add(month)
        paid += 1
        print(f"{report_id}: модель")
print(f"запросов к модели: {paid}")
