"""
Урок 12.3 "Длинный текст по частям", шаг 4

Разбейте текст на части не длиннее заданного числа слов.

В первой строке наибольшее число слов в части, во второй текст, слова в нём разделены пробелами.
Части идут подряд, каждая, кроме последней, содержит ровно заданное число слов.

Выведите `частей: n`, а затем каждую часть строкой `k: слова части`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    3
    продажи книг выросли в июле на треть

Пример вывода:

    частей: 3
    1: продажи книг выросли
    2: в июле на
    3: треть
"""

# Решение
size = int(input())
words = input().split()
parts = [words[i:i + size] for i in range(0, len(words), size)]
print(f"частей: {len(parts)}")
for k, chunk in enumerate(parts, 1):
    print(f"{k}: {' '.join(chunk)}")
