"""
Урок 12.3 "Длинный текст по частям", шаг 5

Смоделируйте аккорд, который пересказывает документ по частям.

В первой строке `max_retries` задачи пересказа части. Дальше до конца ввода по строке на каждую
часть, в ней через пробел ответы модели на попытки этой части. `200` значит, пересказ части готов,
`400` и `404` постоянные ошибки, `429` и `503` временные. Временная ошибка даёт повтор, если
повторов было меньше `max_retries`, иначе часть падает. Лишние ответы после окончания части не
используются.

Для каждой части выведите `часть k: готово` или `часть k: FAILURE`. Затем `запросов к модели: n`, то
есть число всех использованных ответов. Последней строкой `итог собран из n частей`, если все части
готовы, иначе `колбэк не вызван`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    1
    200
    429 200
    503 503 200

Пример вывода:

    часть 1: готово
    часть 2: готово
    часть 3: FAILURE
    запросов к модели: 5
    колбэк не вызван
"""

# Решение
import sys

max_retries = int(input())
requests = 0
done = 0
failed = None
for k, line in enumerate(sys.stdin, 1):
    answers = line.split()
    retries = 0
    result = "FAILURE"
    for answer in answers:
        requests += 1
        if answer == "200":
            result = "готово"
            break
        if answer in ("400", "404") or retries >= max_retries:
            break
        retries += 1
    print(f"часть {k}: {result}")
    if result == "готово":
        done += 1
    elif failed is None:
        failed = k
print(f"запросов к модели: {requests}")
if failed is None:
    print(f"итог собран из {done} частей")
else:
    print("колбэк не вызван")
