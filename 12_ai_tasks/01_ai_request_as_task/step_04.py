"""
Урок 12.1 "Запрос к нейросети как фоновая задача", шаг 4

Очередь `ai` слушает один воркер с `--concurrency 1`. В очереди одновременно оказались несколько
запросов на пересказ. Посчитайте, когда будет готов каждый пересказ.

В строке через пробел время ответа модели в секундах для каждого запроса в порядке очереди. Первый
запрос начинается в момент 0, каждый следующий сразу после окончания предыдущего.

Для каждого запроса выведите `пересказ k: начат в s с, готов в e с`, а последней строкой `последний
пользователь ждал e с`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    4 10 3

Пример вывода:

    пересказ 1: начат в 0 с, готов в 4 с
    пересказ 2: начат в 4 с, готов в 14 с
    пересказ 3: начат в 14 с, готов в 17 с
    последний пользователь ждал 17 с
"""

# Решение
durations = list(map(int, input().split()))
start = 0
for k, d in enumerate(durations, 1):
    print(f"пересказ {k}: начат в {start} с, готов в {start + d} с")
    start += d
print(f"последний пользователь ждал {start} с")
