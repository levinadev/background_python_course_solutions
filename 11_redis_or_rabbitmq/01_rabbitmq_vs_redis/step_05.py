"""
Урок 11.1 "Чем RabbitMQ отличается от Redis", шаг 5

Определите порядок, в котором воркер возьмёт сообщения из очереди RabbitMQ с приоритетами.

В первой строке `x-max-priority` очереди. Дальше до конца ввода идут сообщения в порядке отправки,
имя и приоритет или `-`, если приоритет не указан.

Правила. Сообщение без приоритета считается приоритетом 0; приоритет больше `x-max-priority`
считается равным `x-max-priority`; сообщения с большим приоритетом идут раньше, с равным в порядке
отправки.

Выведите имена в порядке выполнения через пробел. Сравните с задачей о приоритетах в Redis из модуля
про воркеры. Там порядок был обратным.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    10
    p0a 0
    p9a 9
    none -
    p5 5
    p9b 9
    p15 15
    p1 1
    p10 10

Пример вывода:

    p15 p10 p9a p9b p5 p1 p0a none
"""

# Решение
max_priority = int(input())
messages = []
while True:
    try:
        name, priority = input().split()
    except EOFError:
        break
    value = 0 if priority == "-" else min(int(priority), max_priority)
    messages.append((value, name))
order = [name for _, name in sorted(messages, key=lambda m: -m[0])]
print(" ".join(order))
