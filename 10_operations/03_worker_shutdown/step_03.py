"""
Урок 10.3 "Остановка воркеров и продакшен", шаг 3

Смоделируйте, что станет с выполняющимися задачами при остановке контейнера воркера.

В первой строке `stop_grace_period` в секундах и режим подтверждения `early` или `late`. Дальше до
конца ввода идут выполняющиеся задачи, имя и сколько секунд им осталось.

Воркер получает `TERM` и ждёт выполняющиеся задачи; через `stop_grace_period` секунд контейнер
убивают. Задача, которой осталось не больше этого времени, успевает завершиться. `имя: завершится`.
Иначе при `early` она потеряна, `имя: прервана и потеряна`, а при `late`, `имя: прервана, вернётся в
очередь после visibility timeout`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    10 early
    report 40
    email 1

Пример вывода:

    report: прервана и потеряна
    email: завершится
"""

# Решение
grace, mode = input().split()
grace = int(grace)
while True:
    try:
        name, remaining = input().split()
    except EOFError:
        break
    if int(remaining) <= grace:
        print(f"{name}: завершится")
    elif mode == "late":
        print(f"{name}: прервана, вернётся в очередь после visibility timeout")
    else:
        print(f"{name}: прервана и потеряна")
