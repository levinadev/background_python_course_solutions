"""
Урок 2.3 "Очередь своими руками", шаг 6

Смоделируйте очередь задач с одним воркером.

В первой строке число команд, дальше по одной команде в строке.

- `send имя`, поставить задачу в конец очереди и вывести `в очереди: N`, где N это длина очереди
после добавления;
- `work`, воркер берёт задачу из начала очереди. Вывести `выполнена: имя` или `очередь пуста`, если
брать нечего.

После всех команд выведите `осталось в очереди: N`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    4
    send email
    send report
    work
    work

Пример вывода:

    в очереди: 1
    в очереди: 2
    выполнена: email
    выполнена: report
    осталось в очереди: 0
"""

# Решение
from collections import deque

queue = deque()
for _ in range(int(input())):
    command = input().split()
    if command[0] == "send":
        queue.append(command[1])
        print(f"в очереди: {len(queue)}")
    elif queue:
        print(f"выполнена: {queue.popleft()}")
    else:
        print("очередь пуста")
print(f"осталось в очереди: {len(queue)}")
