"""
Урок 2.3 "Очередь своими руками", шаг 3

Несколько воркеров забирают задачи из одной очереди. Задачи берутся строго по порядку. Очередную
задачу забирает воркер, который освободится раньше всех. Если таких воркеров несколько, задачу берёт
воркер с меньшим номером. В момент 0 все воркеры свободны.

В первой строке число воркеров, во второй длительности задач в секундах через пробел, в порядке
очереди.

Для каждой задачи выведите строку `задача i: воркер j, start-end с`, а в конце `все задачи выполнены
за T с`, где T это момент окончания последней задачи.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    2
    5 2 2 1

Пример вывода:

    задача 1: воркер 1, 0-5 с
    задача 2: воркер 2, 0-2 с
    задача 3: воркер 2, 2-4 с
    задача 4: воркер 2, 4-5 с
    все задачи выполнены за 5 с
"""

# Решение
import heapq

workers = int(input())
durations = list(map(int, input().split()))
free = [(0, number) for number in range(1, workers + 1)]
finish = 0
for i, duration in enumerate(durations, 1):
    start, number = heapq.heappop(free)
    end = start + duration
    print(f"задача {i}: воркер {number}, {start}-{end} с")
    heapq.heappush(free, (end, number))
    finish = max(finish, end)
print(f"все задачи выполнены за {finish} с")
