"""
Урок 5.3 "Идемпотентность", шаг 4

Оплаты приходят из очереди, где возможны повторы. Одно и то же сообщение может прийти несколько раз.
Обработайте их идемпотентно.

В первой строке начальный баланс, во второй число сообщений, дальше по сообщению в строке,
идентификатор оплаты и сумма. Каждую оплату нужно зачесть ровно один раз, повторные сообщения с тем
же идентификатором пропускаются.

Выведите `баланс: X` и `повторов пропущено: N`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    1000
    4
    p1 500
    p2 250
    p1 500
    p1 500

Пример вывода:

    баланс: 1750
    повторов пропущено: 2
"""

# Решение
balance = int(input())
processed = set()
duplicates = 0
for _ in range(int(input())):
    payment_id, amount = input().split()
    if payment_id in processed:
        duplicates += 1
        continue
    processed.add(payment_id)
    balance += int(amount)
print(f"баланс: {balance}")
print(f"повторов пропущено: {duplicates}")
