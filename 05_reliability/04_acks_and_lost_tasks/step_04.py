"""
Урок 5.4 "Подтверждение и потеря задач", шаг 4

Смоделируйте, какие задачи брокер Redis доставит повторно.

В первой строке visibility timeout в секундах и режим подтверждения. `early` (по умолчанию) или
`late` (`task_acks_late=True`). Дальше до конца ввода идут задачи, имя, `countdown` в секундах и
длительность выполнения в секундах.

Упрощённая модель. Воркер получает сообщение сразу после отправки. При `early` оно остаётся
неподтверждённым, пока задача ждёт своего `countdown`, при `late`, ещё и всё время выполнения. Если
неподтверждённое время больше visibility timeout, выведите `имя: будет доставлена повторно`, иначе
`имя: один раз`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    3600 early
    reminder 7200 5
    email 0 2

Пример вывода:

    reminder: будет доставлена повторно
    email: один раз
"""

# Решение
timeout, mode = input().split()
timeout = int(timeout)
while True:
    try:
        name, countdown, duration = input().split()
    except EOFError:
        break
    unacked = int(countdown) + (int(duration) if mode == "late" else 0)
    if unacked > timeout:
        print(f"{name}: будет доставлена повторно")
    else:
        print(f"{name}: один раз")
