"""
Урок 8.2 "Один beat и блокировки", шаг 4

Смоделируйте периодическую задачу, защищённую блокировкой с автоматическим снятием.

В первой строке срок блокировки в секундах. Дальше до конца ввода идут события в порядке времени.
Это момент в секундах, имя воркера и `start` (запуск задачи) или `finish` (задача этого воркера
закончилась). Событие `finish` приходит только от воркера, который выполняет задачу.

Блокировка свободна, если её никто не держит или если её срок истёк. Как и в Redis, блокировка,
взятая в момент t, действует до момента t + срок включительно и освобождается после него.

На `start`. Если блокировка свободна, воркер захватывает её, выведите `t: имя запускает очистку`,
иначе `t: имя пропускает, блокировка у владелец`. На `finish`. Если блокировка всё ещё принадлежит
этому воркеру, он снимает её, выведите `t: имя закончил и снял блокировку`, иначе `t: имя закончил,
блокировка уже истекла`.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    10
    0 w1 start
    3 w2 start
    8 w1 finish
    9 w2 start

Пример вывода:

    0: w1 запускает очистку
    3: w2 пропускает, блокировка у w1
    8: w1 закончил и снял блокировку
    9: w2 запускает очистку
"""

# Решение
timeout = int(input())
holder, expires_at = None, 0
running = set()
while True:
    try:
        moment, worker, event = input().split()
    except EOFError:
        break
    moment = int(moment)
    if holder is not None and moment > expires_at:
        holder = None
    if event == "start":
        if holder is None:
            holder, expires_at = worker, moment + timeout
            running.add(worker)
            print(f"{moment}: {worker} запускает очистку")
        else:
            print(f"{moment}: {worker} пропускает, блокировка у {holder}")
    elif worker in running:
        running.discard(worker)
        if holder == worker:
            holder = None
            print(f"{moment}: {worker} закончил и снял блокировку")
        else:
            print(f"{moment}: {worker} закончил, блокировка уже истекла")
