"""
Урок 7.3 "Предвыборка, частота и приоритеты", шаг 5

Посчитайте, что даёт ограничение частоты Celery при нескольких воркерах.

На вход подаётся строка, в ней ограничение (`N/s`, `N/m` или `N/h`), число воркеров и число задач.
Ограничение действует на каждый воркер. Между двумя запусками на одном воркере проходит не меньше
"единица времени / N" секунд. Задачи распределяются по воркерам поровну, первая задача на каждом
воркере стартует сразу.

Выведите `всего не больше X задач в час` (для всех воркеров вместе, целое число) и `последняя задача
стартует не раньше чем через T с` с одним знаком после запятой.

Ввод и вывод. Входные данные читайте функцией `input()`, результат выводите через `print()`. Перед
отправкой нажмите "Запустить код", чтобы проверить решение на своих данных.

Пример ввода:

    60/m 3 9

Пример вывода:

    всего не больше 10800 задач в час
    последняя задача стартует не раньше чем через 2.0 с
"""

# Решение
import math

rate, workers, tasks = input().split()
count, unit = rate.split("/")
workers, tasks = int(workers), int(tasks)
seconds = {"s": 1, "m": 60, "h": 3600}[unit]
per_hour = int(count) * 3600 // seconds * workers
interval = seconds / int(count)
last_start = (math.ceil(tasks / workers) - 1) * interval
print(f"всего не больше {per_hour} задач в час")
print(f"последняя задача стартует не раньше чем через {last_start:.1f} с")
